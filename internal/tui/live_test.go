func realFrontendEngine() (observer.Engine, string, string, string) {
	if os.Getenv("C_OBSERVER_REAL_GDB") == "1" {
		return engine.GDBEngine{}, os.Getenv("C_OBSERVER_TEST_GCC"), os.Getenv("C_OBSERVER_TEST_GDB"), "GDB"
	}
	return engine.Engine{}, os.Getenv("C_OBSERVER_TEST_CLANG"), os.Getenv("C_OBSERVER_TEST_LLDB"), "LLDB"
}

func TestRealEngineReplay(t *testing.T) {
	if os.Getenv("C_OBSERVER_REAL_DEBUGGER") != "1" && os.Getenv("C_OBSERVER_REAL_GDB") != "1" {
		t.Skip("real debugger test is opt-in")
	}
	backend, compiler, debugger, label := realFrontendEngine()
	dir := t.TempDir()
	// Chinese-path support is separately covered by engine tests on a compatible locale.
	name := "课程 example.c"
	if runtime.GOOS == "windows" {
		name = "course example.c"
	}
	src := filepath.Join(dir, name)
	program := `#include <stdio.h>
int main(void) {
    int a[100010] = {0};
    int n, sum = 0;
    scanf("%d", &n);
    for (int i=0; i<n; ++i) {
        scanf("%d", &a[i]);
        sum += a[i];
    }
    printf("%d\n", sum);
    return 0;
}
`
	if err := os.WriteFile(src, []byte(program), 0600); err != nil {
		t.Fatal(err)
	}
	expected := []byte("10\n")
	if runtime.GOOS == "windows" {
		expected = []byte("10\r\n")
	}
	cfg := observer.LaunchConfig{SourcePath: src, WorkDir: dir, Stdin: []byte("3\n3 0 7\n"), ExpectedStdout: &expected, Compiler: compiler, Debugger: debugger}
	result := backend.Run(context.Background(), cfg)
	if result.Reason != observer.Exited || string(result.Output.Stdout) != string(expected) || len(result.Snapshots) < 5 || result.CleanupError != "" {
		t.Fatalf("real run: reason=%s message=%s diagnostics=%+v stdout=%q count=%d cleanup=%s", result.Reason, result.Message, result.Diagnostics, result.Output.Stdout, len(result.Snapshots), result.CleanupError)
	}
	m := NewLive(backend, cfg)
	next, _ := m.Update(runDone{result})
	m = next.(Model)
	if m.err != "" || m.replay.Index == nil || m.demo {
		t.Fatal("real result did not enter replay")
	}
	seenArray := false
	seenReliable := false
	seenFocus := false
	seenChange := false
	for pos := range result.Snapshots {
		m.seek(pos)
		for _, r := range m.replay.Rows(nil) {
			if r.Name == "a" && r.Raw.Kind == observer.Array && len(r.Raw.Children) > 0 {
				seenArray = true
				if r.Reliable {
					seenReliable = true
					f := m.displayFocus(r)
					if f.Automatic && f.Rows.Lo == 0 && f.Rows.Hi == 4 {
						seenFocus = true
					}
				}
				for _, child := range m.replay.Rows(nil) {
					if child.Parent == r.Key && child.Changed {
						seenChange = true
					}
				}
				if !r.Reliable && m.displayFocus(r).Automatic {
					t.Fatal("unreliable real identity cropped")
				}
				table := m.dataTable(r, m.replay.Rows(nil))
				if len(table.Rows) == 0 {
					t.Fatal("real array missing")
				}
			}
		}
		for _, line := range strings.Split(m.View(), "\n") {
			if lipgloss.Width(line) > m.width {
				t.Fatal("render overflow")
			}
		}
	}
	if !seenArray || !seenReliable || !seenFocus || !seenChange {
		t.Fatalf("real adaptive focus: array=%v reliable=%v focus=%v change=%v", seenArray, seenReliable, seenFocus, seenChange)
	}
	next, _ = m.Update(tea.KeyMsg{Type: tea.KeyEnd})
	m = next.(Model)
	if !m.replay.End() || !strings.Contains(m.View(), "输出一致") {
		t.Fatal("final result missing")
	}
	t.Logf("real %s run replayed %d snapshots", label, len(result.Snapshots))
}

// TestCompanionSessionReplay consumes a session generated by actual Companion
// source assembly, not a handwritten approximation of its JSON.
func TestCompanionSessionReplay(t *testing.T) {
	path := os.Getenv("C_OBSERVER_COMPANION_SESSION")
	if path == "" {
		t.Skip("no Companion-generated session")
	}
	cfg, err := session.Load(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(cfg.VisibleSourcePaths) != 1 || len(cfg.SourceMap) == 0 || cfg.ExpectedStdout == nil {
		t.Fatal("fixture must contain mapped original source and expected output")
	}
	backend, compiler, debugger, _ := realFrontendEngine()
	cfg.Compiler, cfg.Debugger = compiler, debugger
	result := backend.Run(context.Background(), cfg)
	if result.Reason != observer.Exited || string(result.Output.Stdout) != string(*cfg.ExpectedStdout) || result.CleanupError != "" {
		t.Fatalf("mapped run: reason=%s message=%s diagnostics=%+v stdout=%q cleanup=%s", result.Reason, result.Message, result.Diagnostics, result.Output.Stdout, result.CleanupError)
	}
	m := NewLive(backend, cfg)
	next, _ := m.Update(runDone{result})
	m = next.(Model)
	if m.err != "" || m.replay.Index == nil || len(result.Snapshots) < 5 {
		t.Fatalf("mapped replay invalid: %s", m.err)
	}
	original, err := os.ReadFile(cfg.VisibleSourcePaths[0])
	if err != nil {
		t.Fatal(err)
	}
	originalLines := strings.Split(string(original), "\n")
	seenArray := false
	seenReliable := false
	seenFocus := false
	seenChange := false
	for pos, snap := range result.Snapshots {
		m.seek(pos)
		if snap.Location.File != cfg.VisibleSourcePaths[0] || snap.Location.Line < 1 || snap.Location.Line > len(originalLines) {
			t.Fatalf("unmapped or helper pause: %+v", snap.Location)
		}
		for _, row := range m.replay.Rows(nil) {
			if row.Name == "a" && row.Raw.Kind == observer.Array && len(row.Raw.Children) > 0 {
				seenArray = true
				if row.Reliable {
					seenReliable = true
					focus := m.displayFocus(row)
					if focus.Automatic && focus.Rows.Lo == 0 && focus.Rows.Hi == 4 {
						seenFocus = true
					}
					for _, child := range m.replay.Rows(nil) {
						if child.Parent == row.Key && child.Changed {
							seenChange = true
						}
					}
				}
				if !row.Reliable && m.displayFocus(row).Automatic {
					t.Fatal("unreliable mapped array must not be cropped")
				}
			}
		}
	}
	if !seenArray || !seenReliable || !seenFocus || !seenChange {
		t.Fatalf("mapped adaptive focus: array=%v reliable=%v focus=%v change=%v", seenArray, seenReliable, seenFocus, seenChange)
	}
	m.seek(len(result.Snapshots))
	if !strings.Contains(m.View(), "输出一致") {
		t.Fatal("mapped final output comparison missing")
	}
	t.Logf("Companion-generated mapped session replayed %d snapshots; verified reliable identity, actual changes and focus 0..4", len(result.Snapshots))
}
