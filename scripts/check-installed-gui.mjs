import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const [root,version,mode]=process.argv.slice(2);
const read=n=>JSON.parse(fs.readFileSync(path.join(root,n),'utf8'));
const pkg=read('package.json'),m=read('manifest.json');
if(pkg.name!=='@routilet/c-observer'||pkg.version!==version||m.version!==version||pkg.scripts||m.schemaVersion!==1||!m.sessionSchemaVersions.includes(1))throw Error('Unexpected package metadata');
if(pkg.repository?.url!=='git+https://github.com/Routilet/c-observer.git')throw Error('Incorrect provenance');
if(mode==='DRY_RUN'?pkg.private!==true:pkg.private===true||pkg.publishConfig?.tag!==(version.includes('-')?'next':'latest'))throw Error('Incorrect release channel');
for(const name of ['LICENSE','THIRD_PARTY_NOTICES.txt'])if(!fs.statSync(path.join(root,name)).size)throw Error('Missing '+name);
if(Object.keys(m.platforms).sort().join(',')!=='darwin-arm64,win32-x64')throw Error('Incorrect supported targets');
for(const e of Object.values(m.platforms))if(createHash('sha256').update(fs.readFileSync(path.join(root,e.executable))).digest('hex')!==e.sha256)throw Error('Checksum mismatch');
const native=m.platforms[process.platform+'-'+process.arch];
if(!native)throw Error('No native app for runner');
const bin=path.join(root,native.executable);
const invoke=(...args)=>execFileSync(bin,args,{encoding:'utf8',timeout:15000,windowsHide:true});
if(invoke('--version').trim()!==version)throw Error('Version mismatch');
const caps=JSON.parse(invoke('--capabilities'));
if(caps.version!==version||!caps.sessionSchemaVersions.includes(1)||!caps.backends.includes(process.platform==='win32'?'gdb-mi':'lldb-dap'))throw Error('Invalid capabilities');
if(process.platform==='darwin')execFileSync('codesign',['--verify','--strict',path.resolve(bin,'../../..')],{stdio:'inherit'});
console.log('Verified installed GUI',process.platform,process.arch,caps);
